# Shared network configuration for the JM10-3588.
#
# The board's eight RJ45 ports are Marvell MV88E6390X switch ports hanging off
# the GMAC in DSA mode (eth1..eth8). eth4 is NOT routed to a physical connector
# on this board, so it must never appear in a bridge -- a bridge-ports entry for
# a port with no PHY makes ifupdown2 fail to bring the bridge up at all.
#
# Two flavours are produced from the same port list:
#
#   plain build      br0 inet dhcp          -- works out of the box
#   PROXMOX=yes      br0 inet static        -- requires explicit parameters
#
# The static parameters are mandatory for PVE on purpose: a PVE host that comes
# up on a guessed address is unreachable and has to be fixed over a console, so
# the build refuses to guess. Pass them on the command line:
#
#   ./compile.sh ... PROXMOX=yes \
#     JM10_NET_BRIDGE_ADDRESS=192.168.9.210/24 \
#     JM10_NET_BRIDGE_GATEWAY=192.168.9.1 \
#     JM10_NET_BRIDGE_DNS=192.168.9.101
#
# end0 (the GMAC/DSA master) is deliberately NOT a bridge port: it is the CPU
# uplink the switch fabric sits behind, and enslaving it under br0 would put
# the management path inside the bridge it is supposed to carry.

# The switch ports that exist on this board, in the order the DSA driver
# enumerates them. eth4 is absent because the board does not route it.
declare -g -a JM10_DSA_PORTS=("eth1" "eth2" "eth3" "eth5" "eth6" "eth7" "eth8")

# Interfaces the image must declare but never enslave: the GMAC master and the
# WiFi clients. eth4 is absent on purpose -- it is not routed to a connector, so
# it is not declared at all, matching a config verified to work on real PVE.
declare -g -a JM10_NET_MANUAL_ONLY=("end0" "wlan0" "wwu1i4")

# Validate the static parameters shared by both network flavours. Empty values
# are allowed (they simply omit that stanza); malformed ones are a build error,
# because they would silently produce an unbootable-network image.
function jm10_net_validate_params() {
	if [[ -n "${JM10_NET_BRIDGE_ADDRESS}" && ! "${JM10_NET_BRIDGE_ADDRESS}" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]]; then
		exit_with_error "JM10_NET_BRIDGE_ADDRESS must be in CIDR form (e.g. 192.168.9.210/24)" \
			"JM10_NET_BRIDGE_ADDRESS=${JM10_NET_BRIDGE_ADDRESS}"
	fi
	if [[ -n "${JM10_NET_BRIDGE_GATEWAY}" && ! "${JM10_NET_BRIDGE_GATEWAY}" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then
		exit_with_error "JM10_NET_BRIDGE_GATEWAY must be an IPv4 address" \
			"JM10_NET_BRIDGE_GATEWAY=${JM10_NET_BRIDGE_GATEWAY}"
	fi
	if [[ -n "${JM10_NET_BRIDGE_DNS}" && ! "${JM10_NET_BRIDGE_DNS}" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]]; then
		exit_with_error "JM10_NET_BRIDGE_DNS must be an IPv4 address" \
			"JM10_NET_BRIDGE_DNS=${JM10_NET_BRIDGE_DNS}"
	fi
}

# Render /etc/network/interfaces for a PVE (ifupdown2) host.
#
# $1 = destination path. Requires JM10_NET_BRIDGE_ADDRESS; the gateway and DNS
# stanzas are emitted only when their parameters are set.
function jm10_net_write_pve_interfaces() {
	local dst="$1"
	[[ -n "${JM10_NET_BRIDGE_ADDRESS}" ]] ||
		exit_with_error "PROXMOX=yes needs an explicit bridge address" \
			"set JM10_NET_BRIDGE_ADDRESS (CIDR), e.g. 192.168.9.210/24"

	jm10_net_validate_params

	display_alert "JM10 network" "PVE vmbr0 static ${JM10_NET_BRIDGE_ADDRESS}" "info"

	{
		echo "# network interface settings; autogenerated by the Armbian build"
		echo "# JM10-3588: Marvell MV88E6390X DSA ports eth1..eth8, eth4 has no"
		echo "# physical connector and is deliberately excluded from the bridge."
		echo "auto lo"
		echo "iface lo inet loopback"
		echo ""
		echo "source /etc/network/interfaces.d/*"
		echo ""
		# Physical ports: brought up automatically so the bridge can enslave them.
		local port
		for port in "${JM10_DSA_PORTS[@]}"; do
			echo "auto ${port}"
			echo "iface ${port} inet manual"
			echo ""
		done
		# Declared but never enslaved.
		local manual
		for manual in "${JM10_NET_MANUAL_ONLY[@]}"; do
			echo "iface ${manual} inet manual"
		done
		echo ""
		echo "auto vmbr0"
		echo "iface vmbr0 inet static"
		echo "	address ${JM10_NET_BRIDGE_ADDRESS}"
		[[ -n "${JM10_NET_BRIDGE_GATEWAY}" ]] && echo "	gateway ${JM10_NET_BRIDGE_GATEWAY}"
		echo "	bridge-ports ${JM10_DSA_PORTS[*]}"
		echo "	bridge-stp off"
		echo "	bridge-fd 0"
		[[ -n "${JM10_NET_BRIDGE_DNS}" ]] && echo "	dns-nameservers ${JM10_NET_BRIDGE_DNS}"
	} > "${dst}"
}

# Render a netplan stanza for a plain (non-PVE) build: the same DSA ports under
# br0, but DHCP. NetworkManager or systemd-networkd renders it, so this is
# netplan YAML rather than ifupdown2 syntax.
#
# $1 = destination path.
function jm10_net_write_netplan_bridge() {
	local dst="$1"
	jm10_net_validate_params

	display_alert "JM10 network" "plain build: br0 DHCP on ${JM10_DSA_PORTS[*]}" "info"

	{
		echo "# Let NetworkManager manage all devices on this system"
		echo "network:"
		echo "  version: 2"
		echo "  renderer: networkd"
		echo "  ethernets:"
		# Every DSA port plus the non-bridged interfaces, all unconfigured: the
		# bridge owns the addresses, the ports just carry frames.
		local port
		for port in "${JM10_DSA_PORTS[@]}" "${JM10_NET_MANUAL_ONLY[@]}"; do
			echo "    ${port}:"
			echo "      dhcp4: no"
			echo "      dhcp6: no"
		done
		echo "  bridges:"
		echo "    br0:"
		echo "      interfaces:"
		for port in "${JM10_DSA_PORTS[@]}"; do
			echo "        - ${port}"
		done
		# Plain builds are DHCP by design. The static parameters are a PVE-only
		# concern and are deliberately ignored here: silently honouring them on a
		# plain build would make the same command line produce two different
		# network modes depending on which board file happens to call in.
		echo "      dhcp4: yes"
		echo "      dhcp6: yes"
		echo "      parameters:"
		echo "        stp: false"
	} > "${dst}"
}
